export function translate(
  language: Language,
  key: TranslationKey,
  values?: Record<string, string | number>,
) {
  let message: string = translations[language][key];
  if (values) {
    for (const [name, value] of Object.entries(values)) {
      message = message.replaceAll(`{${name}}`, String(value));
    }
  }
  return message;
}
